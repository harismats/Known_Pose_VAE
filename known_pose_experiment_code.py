        out = model.forward_pair(batch_d)
        idx = 0
        can = batch["canonical"][idx, 0].numpy()
        xa = batch["x_a"][idx, 0].numpy()
        xb = batch["x_b"][idx, 0].numpy()
        pred_can = (torch.sigmoid(out["canonical_logits_mean"][idx, 0]).cpu().numpy() > 0.5).astype(np.float32)
