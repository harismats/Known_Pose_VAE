def parse_seed_string(text: str) -> List[int]:
    """Parse seed strings such as '0-19' or '0,1,2'."""
    seeds: List[int] = []
    for part in text.replace(" ", "").split(","):
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            seeds.extend(range(int(a), int(b) + 1))
        else:
            seeds.append(int(part))
    return sorted(dict.fromkeys(seeds))


